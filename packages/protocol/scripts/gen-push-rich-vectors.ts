// Captures one sealed push and one signed action as fixed bytes, so the Swift code on the phone (TalosPushCore RichPush) is
// checked against what the TypeScript side really produces, byte for byte. Run: `node scripts/gen-push-rich-vectors.ts`.
// The output is committed; vectors.test.ts opens it again so a change to the seal or the signing input goes red.
import { writeFileSync } from 'node:fs'
import {
  cardNotice,
  createDeviceKey,
  createPhoneKeys,
  richContentFor,
  sealPush,
  shownHash,
  signNativeAct,
  signNativeGrant,
} from '../src/index.ts'

const subtle = globalThis.crypto.subtle
const NOW = Date.parse('2026-11-01T18:00:00.000Z')
const CARD = 'c_01JBF3V7Q8K2M4N6P8R0S2T4V7'
const THREAD = 'general'
const dev = await createDeviceKey()
const phone = await createPhoneKeys()
const raw = async (jwkKey: CryptoKey) => {
  const jwk = await subtle.exportKey('jwk', jwkKey)
  if (!jwk.d) throw new Error('no private scalar')
  return jwk.d
}
const grant = await signNativeGrant({
  deviceId: dev.deviceId,
  devicePrivateKey: dev.privateKey,
  encPub: phone.encPub,
  actPub: phone.actPub,
  nowMs: NOW,
})
const card = {
  kind: 'decision' as const,
  title: 'Archive old drafts?',
  summary: 'Moves 12 drafts to Archive',
  destination: [],
  body: 'Only drafts older than 90 days.',
  fields: [],
  primary_label: 'Archive',
  attachments: [],
} as never
const notice = cardNotice(card)
const reply = await sealPush({
  encPub: phone.encPub,
  deviceId: dev.deviceId,
  kind: 'reply',
  content: richContentFor({
    kind: 'reply',
    text: 'Done. The report is in Drive — café 🚀',
    subtitle: 'General',
    threadId: THREAD,
  }),
})
const approve = await sealPush({
  encPub: phone.encPub,
  deviceId: dev.deviceId,
  kind: 'card',
  cardId: CARD,
  content: richContentFor({
    kind: 'card',
    text: notice.text,
    subtitle: 'General',
    threadId: THREAD,
    card: { id: CARD, risk: 'low', payload_hash: `sha256:${'a'.repeat(64)}` },
  }),
})
const ACT_ID = '01JBF3V7Q8K2M4N6P8R0S2T4V6'
const tapped = new Date(NOW + 60_000).toISOString()
const replyAct = await signNativeAct({
  deviceId: dev.deviceId,
  id: ACT_ID,
  ts: tapped,
  grant,
  body: { a: 'reply', thread_id: THREAD, text: 'On it — "quoted" 🚀' },
  actPrivateKey: phone.act.privateKey,
})
const out = {
  note: 'Generated by scripts/gen-push-rich-vectors.ts. Private scalars are throwaway test keys.',
  now_ms: NOW,
  device_id: dev.deviceId,
  device_public_jwk: dev.publicJwk,
  enc_priv_d: await raw(phone.enc.privateKey),
  enc_pub: phone.encPub,
  act_priv_d: await raw(phone.act.privateKey),
  act_pub: phone.actPub,
  grant: JSON.stringify(grant),
  reply: {
    kind: 'reply',
    thread_id: THREAD,
    envelope: reply,
    shows: { b: 'Done. The report is in Drive — café 🚀', s: 'General', t: THREAD, k: 'reply' },
  },
  approve: {
    kind: 'card',
    card_id: CARD,
    envelope: approve,
    notice: notice.text,
    subtitle: 'General',
    shown: shownHash(notice.text, 'General'),
    payload_hash: `sha256:${'a'.repeat(64)}`,
  },
  act: { id: ACT_ID, ts: tapped, wire: replyAct },
}
writeFileSync(new URL('../fixtures/push-rich/vectors.json', import.meta.url), `${JSON.stringify(out, null, 2)}\n`)
console.log('wrote fixtures/push-rich/vectors.json')
