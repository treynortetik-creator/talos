// Builds the "npm packages bundled into apps/web and apps/mobile" section of THIRD_PARTY_NOTICES.md.
//
//   pnpm --filter @talos-app/web build          # the source maps list what the bundle really contains
//   node scripts/third-party-web.ts             # print the section
//   node scripts/third-party-web.ts --write     # replace the marked section in THIRD_PARTY_NOTICES.md
//   node scripts/third-party-web.ts --check     # exit 1 when the file differs from what the build would give
//
// Package names and versions come from the node_modules paths in apps/web/dist/**/*.map `sources`, plus the Tailwind
// preflight reset (inlined into the built CSS, which has no source map) and the production dependencies of apps/mobile
// (they ship in the iOS app). Each licence text is copied verbatim from the package's own LICENSE/LICENCE/COPYING file;
// nothing is written from memory. Texts that differ only in the copyright line are kept once, with each package's copyright
// line listed. A package with no licence file is listed under its own heading with the licence id from its package.json,
// and the script exits 2 so someone looks at it.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const NOTICES = join(ROOT, 'THIRD_PARTY_NOTICES.md')
const BEGIN = '<!-- BEGIN bundled-npm (generated by scripts/third-party-web.ts; do not edit by hand) -->'
const END = '<!-- END bundled-npm -->'

/** Packages with their own hand-written section in the notices file (fonts reach the app as CSS and woff2, not as JS). */
const SKIP = (name: string) => name.startsWith('@fontsource-variable/') || name.startsWith('@talos-app/')

/** Packages that ship no licence file at all (checked by hand; only their package.json licence field can be listed). */
const NO_FILE_KNOWN = new Set(['react-remove-scroll-bar'])

type Pkg = { name: string; version: string; dir: string; license: string }

function readJson(p: string): Record<string, unknown> {
  return JSON.parse(readFileSync(p, 'utf8')) as Record<string, unknown>
}

function packageAt(dir: string): Pkg {
  const j = readJson(join(dir, 'package.json'))
  const lic =
    j.license ?? (Array.isArray(j.licenses) ? (j.licenses as { type: string }[]).map((l) => l.type).join(' OR ') : '')
  return { name: String(j.name), version: String(j.version), dir, license: String(lic) }
}

function mapFiles(dist: string): string[] {
  const out: string[] = []
  for (const d of [dist, join(dist, 'assets')]) {
    if (existsSync(d)) for (const f of readdirSync(d)) if (f.endsWith('.map')) out.push(join(d, f))
  }
  return out
}

/** Package roots (the `node_modules/<name>` folder) that the web build's source maps point into. */
function bundledRoots(dist: string): Set<string> {
  const roots = new Set<string>()
  for (const m of mapFiles(dist)) {
    const j = readJson(m) as { sources?: string[] }
    for (const s of j.sources ?? []) {
      const abs = resolve(dirname(m), s)
      const i = abs.lastIndexOf('/node_modules/')
      if (i < 0) continue
      const rest = abs.slice(i + '/node_modules/'.length).split('/')
      const name = rest[0]?.startsWith('@') ? `${rest[0]}/${rest[1]}` : rest[0]
      if (name) roots.add(`${abs.slice(0, i)}/node_modules/${name}`)
    }
  }
  return roots
}

const LICENSE_FILE = /^(licen[cs]e|copying)([-._].*)?$/i

function licenceText(dir: string): string | null {
  const f = readdirSync(dir).find((n) => LICENSE_FILE.test(n))
  return f ? readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trimEnd() : null
}

// A real notice line: "Copyright (c) ...", "Copyright 2020 ...", "Copyright Joyent ...". Not licence prose such as
// "COPYRIGHT HOLDERS BE LIABLE" or "copyright notice and this permission notice".
const COPYRIGHT = /^\s*(Copyright\s+(\(c\)|©|\d|(?!Holders|Notice|License|Owner)[A-Z])|©)/

function copyrightLines(text: string): string[] {
  return text
    .split('\n')
    .filter((l) => COPYRIGHT.test(l))
    .map((l) => l.trim())
}

/** Two texts are the same licence when they match once copyright lines and whitespace are ignored. */
function textKey(text: string): string {
  return text
    .split('\n')
    .filter((l) => !COPYRIGHT.test(l))
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()
}

function collect(): Pkg[] {
  const dist = join(ROOT, 'apps/web/dist')
  if (!existsSync(join(dist, 'assets'))) {
    throw new Error('apps/web/dist is missing: run `pnpm --filter @talos-app/web build` first')
  }
  const byDir = new Map<string, Pkg>()
  for (const root of bundledRoots(dist)) {
    const p = packageAt(root)
    if (!SKIP(p.name)) byDir.set(root, p)
  }
  // Tailwind's preflight reset is inlined into the built CSS (no source map, no header comment).
  const tw = join(ROOT, 'apps/web/node_modules/tailwindcss')
  if (existsSync(tw)) byDir.set(tw, packageAt(tw))
  // Production dependencies of the iOS shell.
  const mobile = readJson(join(ROOT, 'apps/mobile/package.json')) as { dependencies?: Record<string, string> }
  for (const name of Object.keys(mobile.dependencies ?? {})) {
    const d = join(ROOT, 'apps/mobile/node_modules', name)
    if (existsSync(d) && !SKIP(name)) byDir.set(d, packageAt(d))
  }
  // The same name@version can sit in several folders (pnpm peer variants): one entry each.
  const seen = new Map<string, Pkg>()
  for (const p of byDir.values()) seen.set(`${p.name}@${p.version}`, seen.get(`${p.name}@${p.version}`) ?? p)
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
}

export function render(pkgs: Pkg[]): { text: string; missing: string[] } {
  const groups = new Map<string, { text: string; members: Pkg[] }>()
  const missing: Pkg[] = []
  for (const p of pkgs) {
    const text = licenceText(p.dir)
    if (text === null) {
      missing.push(p)
      continue
    }
    if (text.includes('```')) throw new Error(`${p.name}: licence text contains a code fence`)
    const key = textKey(text)
    const g = groups.get(key) ?? { text, members: [] }
    g.members.push(p)
    groups.set(key, g)
  }
  const out: string[] = []
  out.push('## npm packages bundled into apps/web and apps/mobile', '')
  out.push(
    "Generated by `node scripts/third-party-web.ts --write` after a web build: the list is every package the build's source",
    'maps point into, plus Tailwind (its preflight reset is inlined into the CSS) and the production dependencies of',
    "`apps/mobile`. Each licence text is copied verbatim from the package's own licence file. Texts that differ only in the",
    "copyright line are kept once; every package's own copyright line is listed with it.",
    '',
  )
  let n = 0
  for (const g of [...groups.values()].sort((a, b) => a.members[0]!.name.localeCompare(b.members[0]!.name))) {
    n++
    const ids = [...new Set(g.members.map((m) => m.license).filter(Boolean))].join(', ') || 'see text'
    out.push(`### Licence text ${n} (${ids})`, '')
    for (const m of g.members) {
      const c = copyrightLines(licenceText(m.dir) ?? '')
      out.push(`- \`${m.name}\` ${m.version}${c.length ? `: ${c.join('; ')}` : ''}`)
    }
    out.push('', '```text', g.text, '```', '')
  }
  if (missing.length) {
    out.push('### No licence file in the package', '')
    for (const m of missing) out.push(`- \`${m.name}\` ${m.version}: package.json says \`${m.license || 'nothing'}\``)
    out.push('')
  }
  return { text: out.join('\n').trimEnd(), missing: missing.map((m) => `${m.name}@${m.version}`) }
}

function splice(file: string, section: string): string {
  const a = file.indexOf(BEGIN)
  const b = file.indexOf(END)
  if (a < 0 || b < a) throw new Error(`THIRD_PARTY_NOTICES.md has no ${BEGIN} ... ${END} markers`)
  return `${file.slice(0, a)}${BEGIN}\n\n${section}\n\n${file.slice(b)}`
}

function main() {
  const mode = process.argv[2]
  const { text, missing } = render(collect())
  if (mode === '--write' || mode === '--check') {
    const cur = readFileSync(NOTICES, 'utf8')
    const next = splice(cur, text)
    if (mode === '--check') {
      if (next !== cur) {
        console.error('THIRD_PARTY_NOTICES.md is out of date: run `node scripts/third-party-web.ts --write`')
        process.exit(1)
      }
    } else writeFileSync(NOTICES, next)
  } else console.log(text)
  const unknown = missing.filter((m) => !NO_FILE_KNOWN.has(m.replace(/@[^@]*$/, '')))
  if (unknown.length) {
    console.error(`no licence file in: ${unknown.join(', ')} (listed by package.json licence only; check by hand)`)
    process.exit(2)
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
