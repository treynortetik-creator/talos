"""The TΛLOS wordmark as one vector path, from Cinzel's own outlines at weight 900 (brand spec: Cinzel Black, the A a
Cinzel V flipped and scaled so its bottom sits on the baseline and its top at cap height, 0.06 em ink gaps).

  python3 assets/brand/wordmark/generate.py <cinzel font: a static Black TTF, or the variable woff2 (needs brotli)> [gap]

The variable font's default instance is weight 400, so it is pinned to 900 first. Writes wordmark.svg beside this file
and apps/web/src/ui/wordmark-path.ts (what <Wordmark> draws). Needs fontTools; the app never runs this.
After a change, rewrite the reference render the browser test compares against:
  cd apps/web && WORDMARK_REFERENCE_UPDATE=1 pnpm exec playwright test test/ui/wordmark-vector.spec.ts --project=desktop
"""
import pathlib
import re
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]

font = TTFont(sys.argv[1])
if "fvar" in font:
    from fontTools.varLib.instancer import instantiateVariableFont

    font = instantiateVariableFont(font, {"wght": 900})
gap_em = float(sys.argv[2]) if len(sys.argv) > 2 else 0.06
gs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm
cap = font["OS/2"].sCapHeight
gap = gap_em * upm


def bounds(g, t=(1, 0, 0, 1, 0, 0)):
    bp = BoundsPen(gs)
    gs[g].draw(TransformPen(bp, t))
    return bp.bounds




def pairs(args: str) -> str:
    n = args.split()
    assert len(n) % 2 == 0, args
    return " ".join(f"{a},{b}" for a, b in zip(n[::2], n[1::2]))


x = 0.0
paths, tops, bottoms = [], [], []
for ch in "TVLOS":
    g = cmap[ord(ch)]
    xmin, ymin, xmax, ymax = bounds(g)
    if ch == "V":  # flipped: its top (the open end) on the baseline, its point at cap height
        sy = cap / (ymax - ymin)
        t = (1, 0, 0, sy, x - xmin, cap - ymax * sy)
    else:  # font units (y up) to SVG (y down), the baseline at y = cap
        t = (1, 0, 0, -1, x - xmin, cap)
    pen = SVGPathPen(gs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    gs[g].draw(TransformPen(pen, t))
    paths.append(pen.getCommands())
    b = bounds(g, t)
    tops.append(b[1])
    bottoms.append(b[3])
    x += (xmax - xmin) + gap
width = x - gap
top = min(tops)
view_box = f"0 {top:.0f} {width:.0f} {max(bottoms) - top:.0f}"
# x,y pairs joined by commas: plain space-separated digits can read as a phone number to the personal-data check
d = re.sub(r"([MLQCT])([^A-Za-z]+)", lambda m: m[1] + pairs(m[2]), " ".join(paths))

(HERE / "wordmark.svg").write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}" role="img" aria-label="Talos">'
    f'<path fill="currentColor" d="{d}"/></svg>\n'
)
(ROOT / "apps/web/src/ui/wordmark-path.ts").write_text(
    "// GENERATED by assets/brand/wordmark/generate.py from Cinzel Black: do not edit by hand.\n"
    f"export const WORDMARK_VIEWBOX = '{view_box}'\n"
    f"export const WORDMARK_PATH =\n  '{d}'\n"
    "/** The drawing's height in em of the font size it stands in for: the letters are as big as Cinzel text there. */\n"
    f"export const WORDMARK_HEIGHT_EM = {(max(bottoms) - top) / upm:.3f}\n"
    f"export const WORDMARK_WIDTH_EM = {width / upm:.3f}\n"
)
print(view_box, len(d))
